"""Write scripts/script_L3_LN.py (the listening script the audio is built from) from the script in level3/drafts/curriculum/Level3_LessonN.md,
so the audio and the lesson text can never drift apart. Voices / names / Whisper spellings / TTS spellings come from cast/cast_L3_LN.json.
Usage: python make_script_L3.py N   (any folder; paths are relative to this file)"""
import sys, re, json, os
N = sys.argv[1]; B = os.path.dirname(os.path.abspath(__file__)); L = os.path.abspath(os.path.join(B, '..', '..', 'curriculum'))
md = open(f'{L}/Level3_Lesson{N}.md').read()
sec = md[md.index('### Listening script'):md.index('### Answer key')]
rows = [(m.group(1), m.group(2).strip()) for m in re.finditer(r'^> \*\*([^*]+):\*\* (.+)$', sec, re.M)]
rows = [r for r in rows if r[0] != 'Audio']
C = json.load(open(f'{B}/cast/cast_L3_L{N}.json'))
assert rows[0][0] == 'Narrator' and rows[-1][0] == 'Narrator', rows[:1] + rows[-1:]
tts = C.get('TTS', {})
lines = [(s, t, tts[t]) if t in tts else (s, t) for s, t in rows[1:-1]]
for s, _ in rows: assert s in C['VOICES'], s
out = f"""# Level 3, Lesson {N} listening script (original text written for this curriculum; invented names).
# GENERATED by ../make_script_L3.py from ../../../curriculum/Level3_Lesson{N}.md + ../cast/cast_L3_L{N}.json. Edit the lesson, then re-run it.
LESSON = {N}
TITLE = {C['TITLE']!r}
VOICES = {C['VOICES']!r}
FEMALE = {set(C['FEMALE'])!r}
NAMES = {set(C.get('NAMES', []))!r}
SAME = {C.get('SAME', {})!r}
INTRO = {rows[0][1]!r}
LINES = [
""" + ''.join(f" {l!r},\n" for l in lines) + f"""]
END = {rows[-1][1]!r}
"""
open(f'{B}/scripts/script_L3_L{N}.py', 'w').write(out)
words = sum(len(t.split()) for _, t in rows)
print(f'script_L3_L{N}.py: {len(lines)} lines + intro/end, {words} words, speakers {sorted(set(s for s, _ in rows))}')
