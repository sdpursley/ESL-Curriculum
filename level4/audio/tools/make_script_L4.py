"""Write scripts/script_L4_LN.py (the listening script the audio will be built from) from the script in level4/curriculum/Level4_LessonN.md,
so the audio and the lesson text can never drift apart. Same format as Level 3 (make_script_L3.py on the audio-handoff branch), plus a
SETTINGS line with the Level 4 audio settings. Voices / names / Whisper spellings / TTS spellings come from cast/cast_L4_LN.json.
Usage: python make_script_L4.py N [LESSON_MD CAST_JSON OUT_DIR]   (default: paths relative to level4/audio/tools)"""
import sys, re, json, os
N = sys.argv[1]; B = os.path.dirname(os.path.abspath(__file__))
if len(sys.argv) > 2: MD, CAST, OUT = sys.argv[2], sys.argv[3], sys.argv[4]
else:
    L = os.path.abspath(os.path.join(B, '..', '..', 'curriculum'))
    MD, CAST, OUT = f'{L}/Level4_Lesson{N}.md', f'{B}/cast/cast_L4_L{N}.json', f'{B}/scripts'
md = open(MD).read()
sec = md[md.index('### Listening script'):md.index('### Answer key')]
rows = [(m.group(1), m.group(2).strip()) for m in re.finditer(r'^> \*\*([^*]+):\*\* (.+)$', sec, re.M)]
rows = [r for r in rows if r[0] != 'Audio']
C = json.load(open(CAST))
assert rows[0][0] == 'Narrator' and rows[-1][0] == 'Narrator', rows[:1] + rows[-1:]
tts = C.get('TTS', {})
lines = [(s, t, tts[t]) if t in tts else (s, t) for s, t in rows[1:-1]]
for s, _ in rows: assert s in C['VOICES'], s
SET = {'EXAG': 0.72, 'CFG': 0.32, 'NARRATOR_EXAG': 0.55, 'NARRATOR_CFG': 0.40, 'PAUSE_SPK': 1.4, 'LENGTH_S': [90, 135]}
out = f"""# Level 4, Lesson {N} listening script (original text written for this curriculum; invented names). NOT RECORDED YET.
# GENERATED by ../make_script_L4.py from ../../curriculum/Level4_Lesson{N}.md + ../cast/cast_L4_L{N}.json. Edit the lesson, then re-run it.
# Voices: clip names in ../REFS_L4.md (Kokoro-82M synthetic reference voices, cloned with Chatterbox). Estimated length: {C.get('ESTIMATE', {}).get('seconds', '?')} s.
LESSON = {N}
TITLE = {C['TITLE']!r}
VOICES = {C['VOICES']!r}
FEMALE = {set(C['FEMALE'])!r}
NAMES = {set(n.lower() for n in C.get('NAMES', []))!r}
SAME = {dict({'okay': 'ok'}, **C.get('SAME', {}))!r}
SETTINGS = {SET!r}
INTRO = {rows[0][1]!r}
LINES = [
""" + ''.join(f" {l!r},\n" for l in lines) + f"""]
END = {rows[-1][1]!r}
"""
os.makedirs(OUT, exist_ok=True); open(f'{OUT}/script_L4_L{N}.py', 'w').write(out)
words = sum(len(t.split()) for _, t in rows)
print(f'script_L4_L{N}.py: {len(lines)} lines + intro/end, {words} words, speakers {sorted(set(s for s, _ in rows))}')
